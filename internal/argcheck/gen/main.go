// Command gen writes ../tables_gen.go from the --help output of the packaged
// tools. Run it from internal/argcheck with `go generate` inside `nix develop`
// (DIRMCP_TOOLS points at the tools manifest).
//
// It reads the option part of each help line (before the description, which
// starts after two spaces or a tab) and records each -x / --long option and
// whether it takes a value. Per-program fixes the parser cannot see are in
// extra below. The denylist in argcheck.go is applied on top at run time.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"regexp"
	"sort"
	"strings"

	"github.com/dafrick/dirmcp/internal/manifest"
)

type opt struct {
	short map[rune]int
	long  map[string]int
}

// Value kinds, as in argcheck.Arity.
const (
	none     = 0
	required = 1
	optional = 2
)

// extra holds options the help parser misses or gets wrong.
var extra = map[string]map[string]int{
	"head": {"-n": required, "-c": required},
	"tail": {"-n": required, "-c": required, "-f": none, "-F": none, "-s": required},
	"rg":   {"-g": required, "-t": required, "-T": required, "-e": required, "-f": required, "-m": required, "-A": required, "-B": required, "-C": required, "-j": required, "-M": required, "-r": required, "-E": required},
	"gawk": {"-f": required, "-v": required, "-F": required, "-e": required, "-i": required, "-b": none, "-c": none, "-C": none, "-g": none, "-h": none, "-n": none, "-N": none, "-O": none, "-P": none, "-r": none, "-s": none, "-S": none, "-t": none, "-V": none, "-I": none},
	"tree": {"-L": required, "-P": required, "-I": required, "-o": required, "-T": required, "-H": required},
	"sed":  {"-i": none, "-l": required, "-e": required, "-f": required},
	"sort": {"-c": none, "-C": none, "-k": required, "-t": required, "-o": required, "-S": required, "-T": required},
}

// digits lists programs that accept the obsolete -NUM form.
var digits = map[string]bool{"head": true, "tail": true}

var (
	optTok = regexp.MustCompile(`^(--?[A-Za-z0-9#?][-A-Za-z0-9_#]*)(\[=[^\]]*\]|=\S*|\[[^\]]*\])?$`)
	split  = regexp.MustCompile(`\t|  +`)
	// OSC hyperlinks and SGR colour codes (coreutils 9.12 adds them).
	escapes = regexp.MustCompile("\x1b\\]8;;[^\x1b]*\x1b\\\\|\x1b\\[[0-9;]*m")
)

func parse(help string) opt {
	o := opt{short: map[rune]int{}, long: map[string]int{}}
	for _, line := range strings.Split(help, "\n") {
		t := strings.TrimLeft(line, " \t")
		if !strings.HasPrefix(t, "-") {
			continue
		}
		// Option part: up to the description. gawk uses tabs between the
		// short and long form, so join tab-separated option groups.
		parts := split.Split(t, -1)
		var optPart []string
		for _, p := range parts {
			if strings.TrimSpace(p) == "" {
				continue // gawk separates columns with several tabs
			}
			if strings.HasPrefix(strings.TrimSpace(p), "-") {
				optPart = append(optPart, p)
				continue
			}
			break
		}
		toks := strings.FieldsFunc(strings.Join(optPart, " "), func(r rune) bool { return r == ' ' || r == ',' })
		var names []string
		kind := none
		for i, tok := range toks {
			m := optTok.FindStringSubmatch(tok)
			if m == nil {
				if len(names) > 0 && i > 0 && kind == none {
					kind = required // "-e script", "-L level"
				}
				continue
			}
			names = append(names, m[1])
			switch {
			case strings.HasPrefix(m[2], "[="), strings.HasPrefix(m[2], "["):
				if kind == none {
					kind = optional
				}
			case strings.HasPrefix(m[2], "="):
				kind = required
			}
		}
		for _, n := range names {
			add(o, n, kind)
		}
	}
	return o
}

func add(o opt, n string, kind int) {
	if strings.HasPrefix(n, "--") {
		if _, ok := o.long[n[2:]]; !ok || kind > o.long[n[2:]] {
			o.long[n[2:]] = kind
		}
		return
	}
	if len(n) == 2 {
		k := kind
		if k == optional {
			k = none // -i[SUFFIX]: the short form takes it attached only
		}
		o.short[rune(n[1])] = k
	}
}

func main() {
	m, err := manifest.Load(os.Getenv("DIRMCP_TOOLS"))
	if err != nil {
		log.Fatal(err)
	}
	var names []string
	for n := range m.Programs {
		if n != "find" { // own checker
			names = append(names, n)
		}
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by gen; DO NOT EDIT.\n// Source: --help of the tools in the manifest. Regenerate: go generate ./internal/argcheck\n\npackage argcheck\n\nvar generated = map[string]Prog{\n")
	for _, n := range names {
		c := exec.Command(m.Programs[n], "--help")
		c.Env = []string{"LC_ALL=C.UTF-8", "TERM=dumb"}
		out, _ := c.CombinedOutput()
		o := parse(escapes.ReplaceAllString(string(out), ""))
		for k, v := range extra[n] {
			add(o, k, v)
		}
		fmt.Fprintf(&b, "%q: {Digits: %v, Short: map[rune]Arity{", n, digits[n])
		var sk []rune
		for r := range o.short {
			sk = append(sk, r)
		}
		sort.Slice(sk, func(i, j int) bool { return sk[i] < sk[j] })
		for _, r := range sk {
			fmt.Fprintf(&b, "%q: %d, ", r, o.short[r])
		}
		b.WriteString("}, Long: map[string]Arity{")
		var lk []string
		for k := range o.long {
			lk = append(lk, k)
		}
		sort.Strings(lk)
		for _, k := range lk {
			fmt.Fprintf(&b, "%q: %d, ", k, o.long[k])
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
